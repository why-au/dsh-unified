// Compose both browser contributions into the one package factory DSH loads.
// Source factories remain separate and independently testable; no bundler needed.
import { readFile, writeFile } from 'node:fs/promises'
const root = new URL('../', import.meta.url)
const pkg = JSON.parse(await readFile(new URL('package.json', root), 'utf8'))
const sources = await Promise.all(['lib/client.js', 'lib/panel-client.js'].map(async (path) => {
  const source = await readFile(new URL(path, root), 'utf8')
  if (!source.includes('window.__ModuleLoader__.load(')) throw new Error(`Missing module factory: ${path}`)
  return source.replace('window.__ModuleLoader__.load(', 'register(')
}))
const result = `// Generated by scripts/build-client.mjs. Edit the source contributions instead.\n(() => {\nconst contributions = [];\nconst register = (entry) => contributions.push(entry);\n${sources.join('\n')}\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(pkg.name)},\n  factory(require) {\n    const modules = contributions.map((entry) => entry.factory(require));\n    return {\n      inject: ${JSON.stringify(['slots', 'locale', 'sessions'])},\n      apply(ctx) { for (const mod of modules) mod.apply(ctx); },\n    };\n  },\n});\n})();\n`
await writeFile(new URL('lib/client.bundle.js', root), result.replace(/[\t ]+$/gm, ''))
console.log('Built unified browser factory (subscriptions + channel hub).')
